 * - `correctAnswer`: The correct answer string (must match one of the options).
 * - Can be used with QuizManager, QuizOptionsSection, and Review screens.
 * - Easily extendable to add fields like imageUrl, hints, or difficulty level.
 * ================================================
 *//*

data class Question(
    val questionText: String,               // Question text displayed in the quiz
    val options: List<String>,      // List of answer options
    val correctAnswer: String       // Correct answer text
